def test_resend_otp(client, app, monkeypatch):

    captured_otps = []

    original_generate = OTPService.generate_otp

    def generate_otp():

        otp = original_generate()

        captured_otps.append(otp)

        return otp

    monkeypatch.setattr(
        OTPService,
        "generate_otp",
        generate_otp
    )

    monkeypatch.setattr(
        "app.utils.email_services.EmailService.send_otp",
        lambda email, otp: True
    )

    # Register
    response = client.post(
        "/api/auth/register",
        json={
            "first_name": "Resend",
            "last_name": "Test",
            "email": "resend@example.com",
            "password": "Password@123"
        }
    )

    assert response.status_code == 201

    first_otp = captured_otps[-1]

    # Resend
    response = client.post(
        "/api/auth/resend-otp",
        json={
            "email": "resend@example.com"
        }
    )

    assert response.status_code == 200

    second_otp = captured_otps[-1]

    # A new OTP should be generated
    assert second_otp != first_otp

    with app.app_context():

        user = User.query.filter_by(
            email="resend@example.com"
        ).first()

        otps = (
            EmailOTP.query
            .filter_by(user_id=user.id)
            .order_by(EmailOTP.created_at.asc())
            .all()
        )

        assert len(otps) == 2



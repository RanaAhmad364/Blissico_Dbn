def get_test_otp(user_id):
    """
    Get the latest unverified OTP for a user.
    """

    return (
        EmailOTP.query
        .filter_by(
            user_id=user_id,
            verified=False
        )
        .order_by(
            EmailOTP.created_at.desc()
        )
        .first()
    )


def get_plain_otp(monkeypatch):
    """
    Capture OTP generated by OTPService.

    This allows us to test OTP verification without
    depending on a real email server.
    """

    generated_otp = {
        "value": None
    }

    original_generate = OTPService.generate_otp

    def generate_otp():
        otp = original_generate()
        generated_otp["value"] = otp
        return otp

    monkeypatch.setattr(
        OTPService,
        "generate_otp",
        generate_otp
    )

    return generated_otp


